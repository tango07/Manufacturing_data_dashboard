# ---------- helpers -----------------------------------------------------------------------------

def write_workbook(path: Path, blocks: list[tuple[str, list[list]]]) -> Path:
    """blocks: list of (title, rows) where rows[0] is the header and the rest are data.
    Each block is written after a title row, one blank row, with a blank row between blocks."""
    wb = openpyxl.Workbook()
    ws = wb.active
    r = 1
    for title, rows in blocks:
        ws.cell(row=r, column=1, value=title)
        r += 2
        for row in rows:
            for c, v in enumerate(row, start=1):
                ws.cell(row=r, column=c, value=v)
            r += 1
        r += 2
    wb.save(path)
    return path


