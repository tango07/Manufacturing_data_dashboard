def test_t22_q4_stratum_rules():
    # Construct runs where the correlation is positive in every stratum of size >= 5 -> "survives".
    rows = []
    for i in range(12):
        plant = "PLT-01" if i < 6 else "PLT-02"
        rows.append(prod_row(f"RUN-{i:06d}", plant=plant, produced=1000, good=900 + i * 5,
                             minutes=400, scheduled=480, machine="MC-04", shift="Day"))
    fact, *_ = _fact_for(rows)
    out = q4_correlations(fact)
    verdicts = {c["pair"]: c["verdict"] for c in out["candidates"]}
    assert verdicts["scrap_rate vs unplanned_downtime_min"] in {"insufficient evidence", "survives",
                                                                 "partially survives", "does not survive"}
    # Strata of 2 runs must be marked too small to judge.
    small = [s for c in out["candidates"] for s in c["strata"] if s["n"] < 5]
    assert small and all(s["judgement"] == "too small to judge" for s in small)


