def _fact_for(prod_rows, dt_rows=None, insp_rows=None, mat_rows=None):
    prod, _ = clean_prod(prod_rows)
    log = ExceptionLog()
    valid = set(prod["Run_ID"])
    dt = clean_table(pd.DataFrame(dt_rows or [], columns=list(DOWNTIME.columns)), DOWNTIME, log,
                     valid_run_ids=valid, raw_run_ids=valid).clean
    insp = clean_table(pd.DataFrame(insp_rows or [], columns=list(INSPECTION.columns)), INSPECTION, log,
                       valid_run_ids=valid, raw_run_ids=valid).clean
    mat = clean_table(pd.DataFrame(mat_rows or [], columns=list(MATERIAL.columns)), MATERIAL, log,
                      valid_run_ids=valid, raw_run_ids=valid).clean
    return build_run_fact(prod, dt, insp, mat), prod, dt, insp, mat


