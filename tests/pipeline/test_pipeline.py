def test_t29_pipeline_is_idempotent(tmp_path):
    out1, out2 = tmp_path / "a", tmp_path / "b"
    d1, d2 = tmp_path / "da.html", tmp_path / "db.html"
    run(SAMPLE, out1, d1)
    run(SAMPLE, out2, d2)
    for name in ("kpis.json", "dq_exceptions.csv", "run_fact.csv"):
        h1 = hashlib.sha256((out1 / name).read_bytes()).hexdigest()
        h2 = hashlib.sha256((out2 / name).read_bytes()).hexdigest()
        assert h1 == h2, name
    assert hashlib.sha256(d1.read_bytes()).hexdigest() == hashlib.sha256(d2.read_bytes()).hexdigest()


